def ascii_name(s, limit, taken, fallback="p"):
    """ASCII, at most `limit` bytes, unique within `taken`."""
    base = re.sub(r"[^A-Za-z0-9_.-]+", "_", s).strip("_") or fallback
    base = base[:limit]
    name, k = base, 2
    while name in taken:
        suffix = f"_{k}"
        name = base[:limit - len(suffix)] + suffix
        k += 1
    taken.add(name)
    return name


def discover(scene, seq_names, seq):
    """{group: [renderer ids]} of this sequence's props, and the particle renderers."""
    mats = {m["id"]: m for m in scene["materials"]}
    groups, particles = {}, []
    for r in scene["renderers"]:
        parts = r["path"].split("/")
        if parts[0] != "Char" or len(parts) < 3:
            continue
        if parts[2] in seq_names:
            if parts[2] != seq or len(parts) < 5:
                continue
            group = parts[3]
        else:
            group = parts[-1]  # something she carries (the cup): its own prop
        if r["kind"] == "particles":
            particles.append(r)
            continue
        if stage_native.is_cast(r, mats):
            continue
        groups.setdefault(group, []).append(r["id"])
    return groups, particles


# ---------------------------------------------------------------- decomposition
def trs(M3):
    """Columns -> (R proper rotation, s per-axis scale); None where degenerate."""
    s = np.linalg.norm(M3, axis=0)
    eps = 1e-7
    small = s < eps
    if small.sum() >= 2:
        return None, s
    cols = M3 / np.where(small, 1, s)
    if small.any():
        a = int(np.argmax(small))
        b, c = (a + 1) % 3, (a + 2) % 3
        cols[:, a] = np.cross(cols[:, b], cols[:, c])
        cols[:, a] /= np.linalg.norm(cols[:, a])
    # orthonormalise (the recording is float32)
    u, _, vt = np.linalg.svd(cols)
    R = u @ vt
    return R, s


def quat_of(R):
    """Rotation matrix -> quaternion (x, y, z, w)."""
    t = np.trace(R)
    if t > 0:
        k = math.sqrt(t + 1.0) * 2
        w, x, y, z = 0.25 * k, (R[2, 1] - R[1, 2]) / k, (R[0, 2] - R[2, 0]) / k, (R[1, 0] - R[0, 1]) / k
    elif R[0, 0] > R[1, 1] and R[0, 0] > R[2, 2]:
        k = math.sqrt(1.0 + R[0, 0] - R[1, 1] - R[2, 2]) * 2
        w, x, y, z = (R[2, 1] - R[1, 2]) / k, 0.25 * k, (R[0, 1] + R[1, 0]) / k, (R[0, 2] + R[2, 0]) / k
    elif R[1, 1] > R[2, 2]:
        k = math.sqrt(1.0 + R[1, 1] - R[0, 0] - R[2, 2]) * 2
        w, x, y, z = (R[0, 2] - R[2, 0]) / k, (R[0, 1] + R[1, 0]) / k, 0.25 * k, (R[1, 2] + R[2, 1]) / k
    else:
        k = math.sqrt(1.0 + R[2, 2] - R[0, 0] - R[1, 1]) * 2
        w, x, y, z = (R[1, 0] - R[0, 1]) / k, (R[0, 2] + R[2, 0]) / k, (R[1, 2] + R[2, 1]) / k, 0.25 * k
    q = np.array([x, y, z, w])
    return q / np.linalg.norm(q)


def quat_rot(q):
    x, y, z, w = q
    return np.array([
        [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
        [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
        [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)],
    ])


def solve_part(track, name):
    """Rest pose, and per frame: bone translation, rotation and the three morph weights."""
    on, M = track["on"], track["M"]
    n = len(on)
    idx = np.nonzero(on)[0]
    dets = np.array([np.linalg.det(M[i, :3, :3]) for i in idx])
    mirror = np.eye(4)
    if (dets < 0).any():
        if not (dets < 0).all():
            print(f"  warning: {name} mirrors on some frames only")
        mirror = np.diag([-1.0, 1, 1, 1])  # baked into the mesh: M' = M diag(-1,1,1)
    Mm = M @ mirror
    Rs, Ss = [None] * n, np.zeros((n, 3))
    for i in idx:
        Rs[i], Ss[i] = trs(Mm[i, :3, :3])
    S_rest = Ss[idx].max(axis=0)
    ratio = np.where(S_rest > 1e-7, Ss / np.where(S_rest > 1e-7, S_rest, 1), 1)
    good = [i for i in idx if Rs[i] is not None]
    rest = max(good, key=lambda i: (ratio[i].min(), -i))
    R_rest, T_rest = Rs[rest], Mm[rest, :3, 3]
    # per frame: hold the nearest valid pose through off / degenerate frames
    R_f, T_f = [None] * n, np.zeros((n, 3))
    last = (Rs[good[0]], Mm[good[0], :3, 3])  # before the first: the first
    for i in range(n):
        if on[i] and Rs[i] is not None:
            last = (Rs[i], Mm[i, :3, 3])
        R_f[i], T_f[i] = last
    W = np.ones((n, 3))
    for i in idx:
        W[i] = np.clip(1 - np.where(S_rest > 1e-7, Ss[i] / np.where(S_rest > 1e-7, S_rest, 1), 1), 0, 1)
    head = SCALE * FLIP @ T_rest
    trans = np.array([SCALE * FLIP @ T_f[i] - head for i in range(n)])
    quats = np.array([quat_of(FLIP @ R_f[i] @ R_rest.T @ FLIP) for i in range(n)])
    for i in range(1, n):  # one hemisphere, so interpolation takes the short way
        if np.dot(quats[i], quats[i - 1]) < 0:
            quats[i] = -quats[i]
    return {"rest": int(rest), "R": R_rest, "T": T_rest, "S": S_rest, "mirror": mirror,
            "head": head, "trans": trans, "quats": quats, "weights": W, "on": on}


# ---------------------------------------------------------------- PMX
def _text(s):
    b = s.encode("utf-16-le")
    return struct.pack("<i", len(b)) + b


def write_pmx(name, textures, vertices, materials, bones, morphs, comment=""):
    """vertices: list of (pos3, nrm3, uv2, bone); materials: dicts with name, tex
    (index or -1), flags, indices (flat list); bones: (name, pos3, parent);
    morphs: (name, [(vertex, offset3)])."""
    out = io.BytesIO()
    w = out.write
    w(b"PMX " + struct.pack("<f", 2.0))
    w(bytes([8, 0, 0, 4, 4, 4, 4, 4, 4]))  # utf-16, no add-UV, 4-byte indices
    for s in (name, name, comment, comment):
        w(_text(s))
    w(struct.pack("<i", len(vertices)))
    for p, nr, uv, b in vertices:
        w(struct.pack("<3f3f2f", *p, *nr, *uv))
        w(bytes([0]) + struct.pack("<i", b))  # BDEF1
        w(struct.pack("<f", 0.0))  # edge scale
    idx = [i for m in materials for i in m["indices"]]
    w(struct.pack("<i", len(idx)))
    w(struct.pack(f"<{len(idx)}i", *idx))
    w(struct.pack("<i", len(textures)))
    for t in textures:
        w(_text(t))
    w(struct.pack("<i", len(materials)))
    for m in materials:
        w(_text(m["name"]) + _text(m["name"]))
        w(struct.pack("<4f3ff3f", 1, 1, 1, 1, 0, 0, 0, 5.0, 0.5, 0.5, 0.5))
        w(bytes([m["flags"]]))
        w(struct.pack("<4ff", 0, 0, 0, 1, 0.0))  # edge
        w(struct.pack("<ii", m["tex"], -1))
        w(bytes([0, 1, 0]))  # sphere off, shared toon 0
        w(_text(""))
        w(struct.pack("<i", len(m["indices"])))
    w(struct.pack("<i", len(bones)))
    for bn, pos, parent in bones:
        w(_text(bn) + _text(bn))
        w(struct.pack("<3fii", *pos, parent, 0))
        w(struct.pack("<H", 0x0002 | 0x0004 | 0x0008 | 0x0010))
        w(struct.pack("<3f", 0, 0, 0))  # tail offset
    w(struct.pack("<i", len(morphs)))
    for mn, offs in morphs:
        w(_text(mn) + _text(mn))
        w(bytes([4, 1]) + struct.pack("<i", len(offs)))
        for v, o in offs:
            w(struct.pack("<i3f", v, *o))
    # display frames: Root (the root bone), 表情 (the morphs), and the parts
    w(struct.pack("<i", 3))
    w(_text("Root") + _text("Root") + bytes([1]) + struct.pack("<i", 1) + bytes([0]) + struct.pack("<i", 0))
    w(_text("表情") + _text("Exp") + bytes([1]) + struct.pack("<i", len(morphs)))
    for k in range(len(morphs)):
        w(bytes([1]) + struct.pack("<i", k))
    w(_text("parts") + _text("parts") + bytes([0]) + struct.pack("<i", len(bones) - 1))
    for k in range(1, len(bones)):
        w(bytes([0]) + struct.pack("<i", k))
    w(struct.pack("<ii", 0, 0))  # rigid bodies, joints
    return out.getvalue()


def read_pmx(b):
    """Minimal PMX 2.x reader: positions, uvs, bone per vertex (BDEF1), indices,
    textures, materials, bones, vertex morphs."""
    p = 0

    def take(n):
        nonlocal p
        v = b[p:p + n]
        p += n
        return v

    assert take(4) == b"PMX "
    take(4)
    g = list(take(take(1)[0]))
    enc = "utf-16-le" if g[0] == 0 else "utf-8"
    addv, vsz, tsz, msz, bsz, mosz = g[1:7]
    fmt = {1: "b", 2: "h", 4: "i"}

    def text():
        return take(struct.unpack("<i", take(4))[0]).decode(enc)

    def ix(sz, unsigned=False):
        f = fmt[sz]
        return struct.unpack("<" + (f.upper() if unsigned and sz < 4 else f), take(sz))[0]

    name = text()
    text(), text(), text()
    nv = struct.unpack("<i", take(4))[0]
    pos, uv, vb = np.zeros((nv, 3)), np.zeros((nv, 2)), np.zeros(nv, int)
    for i in range(nv):
        pos[i] = struct.unpack("<3f", take(12))
        take(12)
        uv[i] = struct.unpack("<2f", take(8))
        take(16 * addv)
        wt = take(1)[0]
        assert wt == 0, "BDEF1 only"
        vb[i] = ix(bsz)
        take(4)
    ni = struct.unpack("<i", take(4))[0]
    idx = [ix(vsz, True) for _ in range(ni)]
    texs = [text() for _ in range(struct.unpack("<i", take(4))[0])]
    mats = []
    for _ in range(struct.unpack("<i", take(4))[0]):
        mn = text()
        text()
        take(16 + 12 + 4 + 12)
        flags = take(1)[0]
        take(16 + 4)
        ti = ix(tsz)
        ix(tsz)
        take(1)
        shared = take(1)[0]
        take(1) if shared else ix(tsz)
        text()
        mats.append({"name": mn, "tex": texs[ti] if ti >= 0 else None, "flags": flags,
                     "count": struct.unpack("<i", take(4))[0]})
    bones = []
    for _ in range(struct.unpack("<i", take(4))[0]):
        bn = text()
        text()
        bp = struct.unpack("<3f", take(12))
        parent = ix(bsz)
        take(4)
        fl = struct.unpack("<H", take(2))[0]
        take(bsz) if fl & 1 else take(12)
        assert not fl & ~0x1F, "plain bones only"
        bones.append({"name": bn, "pos": np.array(bp), "parent": parent})
    morphs = {}
    for _ in range(struct.unpack("<i", take(4))[0]):
        mn = text()
        text()
        _panel, kind = take(2)
        assert kind == 1
        offs = []
        for _ in range(struct.unpack("<i", take(4))[0]):
            v = ix(vsz, True)
            offs.append((v, np.array(struct.unpack("<3f", take(12)))))
        morphs[mn] = offs
    return {"name": name, "pos": pos, "uv": uv, "bone": vb, "indices": idx, "textures": texs,
            "materials": mats, "bones": bones, "morphs": morphs}


# ---------------------------------------------------------------- VMD
LINEAR = bytes([20, 20, 20, 20, 20, 20, 20, 20, 107, 107, 107, 107, 107, 107, 107, 107])
BONE_INTERP = b"".join(LINEAR[k:] + bytes(k) for k in range(4))


def _sjis(s, n):
    b = s.encode("shift_jis")
    if len(b) > n:
        raise ValueError(f"VMD name {s!r} is over {n} bytes")
    return b + bytes(n - len(b))


def write_vmd(model, bone_keys, morph_keys):
    """bone_keys: (name, frame, pos3, quat xyzw); morph_keys: (name, frame, weight)."""
    out = io.BytesIO()
    out.write(_sjis("Vocaloid Motion Data 0002", 30))
    mb = model.encode("shift_jis")[:20]
    out.write(mb + bytes(20 - len(mb)))
    out.write(struct.pack("<I", len(bone_keys)))
    for bn, f, p, q in bone_keys:
        out.write(_sjis(bn, 15) + struct.pack("<I3f4f", f, *p, *q) + BONE_INTERP)
    out.write(struct.pack("<I", len(morph_keys)))
    for mn, f, wt in morph_keys:
        out.write(_sjis(mn, 15) + struct.pack("<If", f, wt))
    out.write(struct.pack("<III", 0, 0, 0))  # camera, light, shadow
    out.write(struct.pack("<I", 0))  # IK
    return out.getvalue()


def read_vmd(b):
    p = 30
    model = b[p:p + 20].split(b"\0")[0].decode("shift_jis", "replace")
    p += 20
    nb = struct.unpack_from("<I", b, p)[0]
    p += 4
    bones = {}
    for _ in range(nb):
        bn = b[p:p + 15].split(b"\0")[0].decode("shift_jis")
        f, *v = struct.unpack_from("<I3f4f", b, p + 15)
        assert b[p + 47:p + 111] == BONE_INTERP
        bones.setdefault(bn, []).append((f, np.array(v[:3]), np.array(v[3:])))
        p += 111
    nm = struct.unpack_from("<I", b, p)[0]
    p += 4
    morphs = {}
    for _ in range(nm):
        mn = b[p:p + 15].split(b"\0")[0].decode("shift_jis")
        f, wt = struct.unpack_from("<If", b, p + 15)
        morphs.setdefault(mn, []).append((f, wt))
        p += 23
    for d in (bones, morphs):
        for k in d:
            d[k].sort(key=lambda e: e[0])
    return {"model": model, "bones": bones, "morphs": morphs}


def keep_frames(vals, tol=1e-6):
    """Frames to key: where the value differs from either neighbour (holds keep
    their two ends), plus the first and last."""
    n = len(vals)
    keep = []
    for i in range(n):
        if i == 0 or i == n - 1:
            keep.append(i)
            continue
        if np.abs(vals[i] - vals[i - 1]).max() > tol or np.abs(vals[i] - vals[i + 1]).max() > tol:
            keep.append(i)
    return keep


