"""One recorded DLC sequence as a reze-design scene zip - what reze-design's own
"Export scene" writes and "Import scene" reads: scene.json beside its files.

    python agtools/dlc_reze_scene.py AG_dlc_play/<skin>-<角色>-<皮肤名> [--seq touch1 ...] [--verify]
    python ag.py reze AG_dlc_play/<skin>-<角色>-<皮肤名>

Reads the recording the compare page plays (web/data: AGDlcRecord's scene.json,
<seq>.frames.jsonl/.bin, dlc_web.py's translated shaders) and the earlier
pipeline's AG_dlc_scene/<skin>/<seq>/{character.vmd,camera.vmd,audio.wav}. Writes, per sequence,
<dlc>/reze/<dlc>-<seq>.zip:

    scene.json                 a scene PATCH (reze-design lib/scene-patch.ts):
                               "patch": true, so Import merges it into the open
                               scene - her model and materials stay, her motion
                               becomes character.vmd (assets.castMotion) - and
                               only the fields below are written; props and effects
                               carry origin/stage = <dlc>, so touch2 over touch1
                               replaces touch1's
    stage/                     the static game stage (stage_native.py), named by
                               assets.nativeStage
    props/<name>/<name>.pmx    one prop per moving object group of the sequence
    props/<name>/<name>.vmd    its motion: a bone per part, scale + on/off as morphs
    props/<name>/look.json     the game's materials (engine setModelNativeLook),
                               named by the prop's `look`
    props/<name>/tex/ shaders/ what the PMX and the look name
    character.vmd camera.vmd audio.wav
                               her retargeted motion (face included), the camera
                               and the voice: all three, or none when any is
                               missing (the scene then keeps its own)

    props/particle_emitters/   the particle systems' emitters as ps<k>_NNN point
                               bones, particle_emitters.lights.json (each effect's
                               WGSL, pictures and class) and particles/*.png
                               (dlc_particles.py); the effects themselves are in
                               settings.background.effects, by value

Props are the renderers under the character's root (Char/<root>/...) that are
neither the character (SimPipeline/Character/* materials) nor particle systems:
one prop per group folder under Char/<root>/<seq>/<group>/, and one per renderer
she carries elsewhere in her hierarchy (the cup). Particle systems - hers and the
stage's - become reze effects generated by reze-design's own particleEffectWgsl
(dlc_particles.py); a mesh particle holding one still particle (X306a's hologram
sphere) becomes a prop at its recorded pose. The character herself is not in the
scene - the user's model is - but her motion is: character.vmd, retargeted for
the user's models, lands on the scene's first cast member.

Coordinates: game (x, y, z) -> PMX (-x, y, -z) * 8, a half turn about Y (winding
and handedness unchanged), the map the camera VMDs use. UV v -> 1 - v.

A part's motion is its world matrix per frame, T R S. The PMX holds the part at a
rest pose (a frame it is on, at each axis's largest scale); its bone carries
T and R as VMD keys; S, which VMD cannot key, is three vertex morphs per part
(<part>_sx/_sy/_sz, weight w scales that rest-local axis by 1 - w), and a part
that is off has all three at 1 - collapsed onto its bone.
"""
