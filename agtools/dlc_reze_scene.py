# ---------------------------------------------------------------- recording
def mat4(a):
    """Column-major 16 -> row-major 4x4."""
    return np.array(a, dtype=np.float64).reshape(4, 4).T


def load_frames(data, seq):
    frames = [json.loads(l) for l in open(os.path.join(data, f"{seq}.frames.jsonl"), encoding="utf-8") if l.strip()]
    blob = open(os.path.join(data, f"{seq}.frames.bin"), "rb").read()
    return frames, blob


def dense_tracks(frames, blob, scene, rids):
    """Per renderer: on[n] (bool), M[n,4,4] (game world, row-major), and its full
    record state per frame (mats, mpb, layerBits). Skinned renderers (one bone):
    bone localToWorld x bindpose[0]."""
    meshes = {m["id"]: m for m in scene["meshes"]}
    rends = {r["id"]: r for r in scene["renderers"]}
    n = len(frames)
    out = {}
    for rid in rids:
        r = rends[rid]
        on = np.zeros(n, bool)
        M = np.tile(np.eye(4), (n, 1, 1))
        states = []
        cur, have = {}, False
        bp = None
        if r["kind"] == "skinned":
            bps = meshes[r["mesh"]].get("bindposes") or []
            if len(bps) != 1:
                print(f"  warning: {r['path']} has {len(bps)} bones; the prop follows bone 0 only")
            bp = mat4(bps[0]) if bps else np.eye(4)
        for i, fr in enumerate(frames):
            rec = fr["r"].get(rid)
            if rec:
                cur.update({k: v for k, v in rec.items() if k not in ("bones", "particles", "blend")})
                if r["kind"] == "skinned" and rec.get("bones"):
                    off, _cnt = rec["bones"]
                    bone = mat4(np.frombuffer(blob, np.float32, 16, off).astype(np.float64))
                    cur["_M"] = bone @ bp
                    have = True
            if r["kind"] == "skinned":
                on[i] = bool(cur.get("on")) and have
                if have:
                    M[i] = cur["_M"]
            else:
                on[i] = bool(cur.get("on")) and "m" in cur
                if "m" in cur:
                    M[i] = mat4(cur["m"])
            states.append(cur)
            cur = dict(cur)
        out[rid] = {"on": on, "M": M, "states": states}
    return out


